def main():
    p = "work/eboot_jp/eboot_work.json"
    rows = json.load(open(p, encoding="utf-8"))
    hit = miss = 0
    misses = []
    for r in rows:
        kr = M.get(r["jp"])
        if kr is not None:
            r["kr"] = kr
            hit += 1
        else:
            miss += 1
            misses.append(r["jp"])
    json.dump(rows, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"채움 {hit} / 누락 {miss}")
    for m in misses[:40]:
        print(f"  [누락] {m!r}")


if __name__ == "__main__":
    main()
